"""Derive the reduced smoke profile of bp_matched_matrix.mpc (constants only).

Smoke profile: 1 epoch, 2 batches of 128 + 1 batch of 8 (264 training samples),
100 validation and 100 test samples. Everything else is textually identical.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mpc/programs/bp/bp_matched_matrix.mpc"
SMOKE = ROOT / "mpc/programs/bp/bp_matched_matrix_smoke.mpc"
REPLACEMENTS = [
    ("TRAIN, VALIDATION, TEST = 5000, 1000, 1000", "TRAIN, VALIDATION, TEST = 264, 100, 100"),
    ("FULL_BATCHES = 39\n", "FULL_BATCHES = 2\n"),
    ("EPOCHS = 5\n", "EPOCHS = 1\n"),
]


def render():
    text = SOURCE.read_text(encoding="utf-8")
    for old, new in REPLACEMENTS:
        if text.count(old) != 1:
            raise SystemExit(f"expected exactly one occurrence of {old!r}")
        text = text.replace(old, new)
    return "# SMOKE PROFILE generated by scripts/generate_matrix_bp_smoke.py -- do not edit.\n" + text


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(0 if SMOKE.read_text(encoding="utf-8") == render() else 1)
    SMOKE.write_text(render(), encoding="utf-8")
    print(SMOKE)
